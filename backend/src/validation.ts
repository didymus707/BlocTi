import { z } from "zod";

// Mirrors frontend/src/sei/domain/events.ts. The server checks shape and
// time; the frontend resolver checks that a transition is legal.

const id = z.string().trim().min(1).max(200);
const reason = z.string().max(500).optional();
const seconds = z.number().int().min(0).max(7 * 24 * 3600);

const base = {
  eventId: id.optional(), // generated by the server when absent
  blockId: id,
  sessionId: id,
  actor: z.enum(["human", "agent"]),
  source: z.enum(["timer", "agent_hook", "git", "calendar"]),
  evidence: z.enum(["observed", "inferred"]),
  occurredAt: z.string().datetime({ offset: true }).optional(), // defaults to server time
  userId: z.string().optional(), // ignored: the server uses the caller's id
};

const taskEvent = <T extends string>(type: T) =>
  z.object({ ...base, type: z.literal(type), taskId: id }).strict();

export const eventInputSchema = z.discriminatedUnion("type", [
  z
    .object({
      ...base,
      type: z.literal("BlockPlanned"),
      name: z.string().max(200),
      plannedDuration: seconds,
      tasks: z
        .array(
          z.object({ taskId: id, title: z.string().max(500), plannedDuration: seconds }).strict(),
        )
        .max(200),
    })
    .strict(),
  z.object({ ...base, type: z.literal("BlockStarted") }).strict(),
  z.object({ ...base, type: z.literal("BlockPaused"), reason }).strict(),
  z.object({ ...base, type: z.literal("BlockResumed"), reason }).strict(),
  z.object({ ...base, type: z.literal("BlockCompleted") }).strict(),
  taskEvent("TaskStarted"),
  z.object({ ...base, type: z.literal("TaskPaused"), taskId: id, reason }).strict(),
  taskEvent("TaskResumed"),
  taskEvent("TaskCompleted"),
  taskEvent("TaskSkipped"),
  z
    .object({ ...base, type: z.literal("TaskSwitched"), fromTaskId: id, toTaskId: id })
    .strict(),
  z
    .object({
      ...base,
      type: z.literal("SessionTerminated"),
      reason: z.enum(["user_exit", "completed", "interrupted"]),
    })
    .strict(),
]);

export type EventInput = z.infer<typeof eventInputSchema>;

export const appendRequestSchema = z
  .object({ events: z.array(eventInputSchema).min(1).max(50) })
  .strict()
  .refine((body) => new Set(body.events.map((e) => e.blockId)).size === 1, {
    message: "all events in one request must belong to the same block",
    path: ["events"],
  });

export const idempotencyKeySchema = z.string().trim().min(1).max(200);

const taskPlanSchema = z
  .object({ id, name: z.string().max(500), blockId: id, order: z.number().int().min(0), plannedDuration: seconds })
  .strict();

export const savePlanSchema = z
  .object({
    block: z
      .object({
        id,
        name: z.string().max(200),
        userId: z.string().optional(),
        taskIds: z.array(id).max(200).optional(),
        createdAt: z.string().datetime({ offset: true }),
        plannedDuration: seconds,
      })
      .strict(),
    tasks: z.array(taskPlanSchema).max(200),
  })
  .strict();
